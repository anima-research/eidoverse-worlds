import { sock, show } from "./atk-access-lib.ts";
const M = "eidoverse/assets/models/crate_large_blue.glb";
const BALL = "atk-ball-" + Date.now().toString(36);
const log = (t, r) => console.log(`  ${t.padEnd(44)} ${show(r)}`);
let o = await sock(); await o.join("gym","marigold");
log("create ball near spawn", await o.req("create",{id:BALL,model:M,components:{physics:{kind:"dynamic",who:"visitor"},grabbable:{who:"visitor"}},place:{at:[1,8]}}));
o.close();
let A=await sock(); await A.join("gym","atk-grab-A");
let B=await sock(); await B.join("gym","atk-grab-B");
log("A arrive @spawn", await A.req("move",{to:[0,0,8],teleport:true}));
log("B arrive @spawn", await B.req("move",{to:[0,0,8],teleport:true}));
log("A step to ball", await A.req("move",{to:[1,0,8]}));
log("B step to ball", await B.req("move",{to:[1,0,8]}));
log("A grab", await A.req("grab",{id:BALL}));
log("B grab same (CONTENTION)", await B.req("grab",{id:BALL}));
A.close(); await new Promise(r=>setTimeout(r,900));
let C=await sock(); await C.join("gym","atk-grab-C");
await C.req("move",{to:[0,0,8],teleport:true}); await C.req("move",{to:[1,0,8]});
log("C grab after A dropped socket (EXPIRY)", await C.req("grab",{id:BALL}));
log("C put", await C.req("put",{id:BALL}));
log("B grab now", await B.req("grab",{id:BALL}));
await B.req("put",{id:BALL});
B.close(); C.close();
let o2=await sock(); await o2.join("gym","marigold"); await o2.req("delete",{id:BALL}); o2.close();
